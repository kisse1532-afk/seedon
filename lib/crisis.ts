/* 띄어쓰기를 지우고 비교한다. "죽고 싶어"와 "죽고싶어"를 둘 다 잡으려고. */
const SIGNALS = [
  // 스스로 다치거나 죽고 싶다는 말
  "죽고싶", "죽을래", "죽어버리", "자살", "자해", "극단적", "사라지고싶", "살기싫", "그만살",
  "없어지고싶", "손목긋", "뛰어내리",
  // 맞거나 위험한 상황
  "때려요", "때려서", "때렸", "맞아요", "맞고있", "폭행", "학대", "성폭력", "성추행", "협박",
  // 지낼 곳이 없는 상황
  "가출", "집나왔", "집을나왔", "쫓겨났", "쫓겨날", "잘곳이없", "잘데가없", "잘데없", "갈곳이없", "갈데가없",
];

export function hasCrisisSignal(text: string | null | undefined): boolean {
  if (!text) return false;
  const t = text.replace(/\s+/g, "");
  return SIGNALS.some((w) => t.includes(w));
}
