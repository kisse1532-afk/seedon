/**
 * 사는 시/도.
 *
 * 지자체 프로그램은 지역이 다르면 아예 신청이 안 된다(경기도 생활장학금은
 * 경기도 사는 사람만, 서울시 그룹활동은 서울 사람만). 그래서 지역을 모르면
 * 못 쓰는 걸 계속 보여주게 된다.
 *
 * 시/군/구까지는 받지 않는다. 시도 단위면 목적이 달성되고, 더 받으면 그만큼
 * 사는 곳이 좁혀진다.
 */
export const REGIONS = [
  "서울",
  "경기",
  "인천",
  "부산",
  "대구",
  "광주",
  "대전",
  "울산",
  "세종",
  "강원",
  "충북",
  "충남",
  "전북",
  "전남",
  "경북",
  "경남",
  "제주",
] as const;

export type Region = (typeof REGIONS)[number];

/**
 * 프로그램 글에서 이 지역을 가리키는 말.
 * "경기"만 찾으면 "경기도"는 걸리지만 "경기 북부"도 걸린다 — 둘 다 맞으니 괜찮다.
 */
export function regionAliases(region: string): string[] {
  const extra: Record<string, string[]> = {
    서울: ["서울시", "서울특별시"],
    경기: ["경기도"],
    인천: ["인천시", "인천광역시"],
    부산: ["부산시", "부산광역시"],
    대구: ["대구시", "대구광역시"],
    광주: ["광주시", "광주광역시"],
    대전: ["대전시", "대전광역시"],
    울산: ["울산시", "울산광역시"],
    세종: ["세종시", "세종특별자치시"],
    강원: ["강원도", "강원특별자치도"],
    충북: ["충청북도"],
    충남: ["충청남도"],
    전북: ["전라북도", "전북특별자치도"],
    전남: ["전라남도"],
    경북: ["경상북도"],
    경남: ["경상남도"],
    제주: ["제주도", "제주특별자치도"],
  };
  return [region, ...(extra[region] ?? [])];
}
